import assert from 'node:assert/strict';
import path from 'node:path';

// The caller supplies an isolated owner session and two explicitly owned fixture projects.
export async function verifyDirectoryInterface({ page, context, origin, projectId, teamId, output, pass }) {
  await page.goto(origin + '/projects');
  await page.getByRole('heading', { name: '所有项目', exact: true }).waitFor();
  await page.getByRole('button', { name: '已归档', exact: true }).click();
  await page.getByRole('link', { name: '已归档界面验收示例', exact: true }).waitFor();
  assert.equal(await page.locator('[data-project-directory] li').count(), 1);
  await page.getByRole('button', { name: '进行中', exact: true }).click();
  await page.getByLabel('搜索项目').fill('不会存在的界面验收项目');
  await page.getByRole('heading', { name: '没有符合条件的项目' }).waitFor();
  await page.getByRole('button', { name: '清除筛选' }).click();
  assert.equal(await page.locator('[data-project-directory] li').count(), 2);
  await page.getByLabel('项目排序', { exact: true }).selectOption('name');
  await page.getByLabel('项目所属团队', { exact: true }).selectOption(teamId);
  await page.screenshot({ path: path.join(output, 'projects.png'), fullPage: true });
  pass('项目目录真实计数、状态与关键词筛选、排序和清除筛选');
  const link = page.locator('li').filter({ has: page.getByRole('link', { name: '交互设计文档试用', exact: true }) }).getByRole('link', { name: '文档', exact: true });
  await link.click(); await page.waitForURL(`**/projects/${projectId}/documents`);
  pass('项目卡片直接进入当前项目文档');
  await page.goto(origin + '/teams');
  const directory = page.locator('[data-team-directory]');
  await directory.getByText('3', { exact: true }).first().waitFor();
  await page.getByLabel('我的团队角色').selectOption('teacher');
  await page.getByRole('heading', { name: '没有符合条件的团队' }).waitFor();
  await page.getByRole('button', { name: '清除筛选' }).click();
  await page.getByLabel('搜索团队').fill('文档协作');
  assert.equal(await directory.locator('li').count(), 1);
  await context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin });
  await page.getByRole('button', { name: '复制邀请码' }).click();
  await page.getByText('已复制', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), await directory.locator('code').innerText());
  await page.getByRole('button', { name: '创建团队', exact: true }).click();
  await page.getByLabel('团队名称', { exact: true }).waitFor();
  await page.getByRole('button', { name: '加入团队', exact: true }).click();
  await page.getByLabel('团队邀请码').fill('invalid-owned-interface-qa');
  await page.getByRole('button', { name: '确认加入' }).click();
  await page.getByRole('alert').getByText('邀请码无效', { exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, 'teams.png'), fullPage: true });
  pass('团队成员项目计数、角色筛选、邀请码复制与加入错误反馈');
  await page.goto(origin + '/notifications');
  await page.locator('[data-notification-id]').first().waitFor();
  await page.getByLabel('通知项目范围').selectOption(projectId);
  await page.getByRole('button', { name: '应用筛选', exact: true }).click();
  await page.getByRole('button', { name: '本项目全部已读', exact: true }).waitFor();
  assert.equal(await page.locator('[data-notification-id]').count(), 1);
  const source = page.getByRole('link', { name: '查看来源', exact: true });
  assert((await source.getAttribute('href')).startsWith(`/projects/${projectId}`));
  await page.getByRole('button', { name: '本项目全部已读', exact: true }).click();
  await page.getByText('已读', { exact: true }).waitFor();
  const unread = await page.evaluate(async () => (await fetch('/api/notifications/unread-count')).json());
  assert.equal(unread.count, 1);
  pass('通知按项目筛选、来源链接及项目范围批量已读不影响其他项目');
  await page.getByLabel('通知项目范围').selectOption('');
  await page.getByRole('button', { name: '应用筛选', exact: true }).click();
  await page.getByRole('link', { name: '只看未读', exact: true }).click();
  await page.locator('nav[aria-label="通知状态"] a[aria-current="page"][href*="unreadOnly=true"]').waitFor();
  assert.equal(await page.locator('[data-notification-id]').count(), 1);
  await page.screenshot({ path: path.join(output, 'notifications.png'), fullPage: true });
  await page.getByRole('button', { name: '标记已读', exact: true }).click();
  await page.getByRole('heading', { name: '没有未读通知', exact: true }).waitFor();
  pass('通知未读过滤、单条已读和空状态');
  await page.goto(origin + '/projects');
  await page.locator('summary[aria-label="新手教程菜单"]').click();
  await page.getByRole('button', { name: '当前页面操作指引', exact: true }).click();
  await page.locator('.driver-popover').waitFor();
  await page.keyboard.press('Escape');
  await page.locator('.driver-popover').waitFor({ state: 'hidden' });
  await page.locator('summary[aria-label="新手教程菜单"]').click();
  await page.getByRole('link', { name: '使用指南与角色流程', exact: true }).click();
  await page.getByRole('heading', { name: 'AgileCampus 使用指南', exact: true }).waitFor();
  await page.locator('summary').getByText('指导教师', { exact: true }).click();
  await page.getByRole('heading', { name: '审阅文档', exact: true }).waitFor();
  await page.getByRole('navigation', { name: '使用指南目录' }).getByRole('link', { name: /项目文档协作/ }).click();
  await page.screenshot({ path: path.join(output, 'tutorial.png'), fullPage: false });
  pass('页面指引统一纳入教程菜单、指引可退出、正式教程角色与目录可访问');
  for (const width of [1366, 1440]) {
    await page.setViewportSize({ width, height: 1000 }); await page.goto(origin + '/projects');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  }
  pass('1366与1440桌面宽度无横向页面溢出');
}
